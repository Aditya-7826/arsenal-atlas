#!/usr/bin/env node
/**
 * Quality report for public/models/*.glb -> data/MODEL-REPORT.md
 *
 * For each model: size (MB), triangles, texture count, largest texture.
 * Flags: 0 textures, > 20 MB, > 300k triangles. Models over 300k triangles get a
 * second pass from models-raw/ with simplify (ratio 0.5, error 0.001); the result
 * replaces public/models/<id>.glb and the report shows before and after.
 *
 *   npm run models:report
 */
import { spawnSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(root, 'public', 'models')
const RAW = join(root, 'models-raw')
const cli = join(root, 'node_modules', '@gltf-transform', 'cli', 'bin', 'cli.js')
const TRI_LIMIT = 300_000
const MB_LIMIT = 20
const WATCH = ['l96a1', 'mk14-ebr', 'winchester-1873', 'm60', 'scar-h']

const names = new Map(JSON.parse(readFileSync(join(root, 'data', 'firearms.json'), 'utf8')).map((f) => [f.id, f.name]))

function run(args) {
  const r = spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  if (r.status !== 0) throw new Error((r.stderr || r.stdout).trim())
  return r.stdout
}

// terminal colour codes, built without a literal control character
const ANSI = new RegExp(`${String.fromCharCode(27)}\\[[0-9;]*m`, 'g')

/** Split `inspect --format csv` output into { SECTION: rows[] }. */
function parseInspect(text) {
  const sections = {}
  let cur = null
  let header = null
  const splitCsv = (line) => {
    const out = []
    let f = ''
    let q = false
    for (const ch of line) {
      if (ch === '"') q = !q
      else if (ch === ',' && !q) {
        out.push(f)
        f = ''
      } else f += ch
    }
    out.push(f)
    return out
  }
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(ANSI, '').trimEnd()
    const title = line.trim()
    if (/^[A-Z]+$/.test(title)) {
      cur = title
      sections[cur] = []
      header = null
      continue
    }
    if (!cur || !title || title.startsWith('─') || title.startsWith('No ')) continue
    const cells = splitCsv(title)
    if (!header) header = cells
    else sections[cur].push(Object.fromEntries(header.map((h, i) => [h, cells[i]])))
  }
  return sections
}

function stats(file) {
  const s = parseInspect(run(['inspect', file, '--format', 'csv']))
  const tris = (s.MESHES ?? [])
    .filter((m) => m.mode === 'TRIANGLES')
    .reduce((t, m) => t + Number(m.glPrimitives || 0) * Number(m.instances || 1), 0)
  const textures = s.TEXTURES ?? []
  let largest = null
  for (const t of textures) {
    const [w, h] = (t.resolution ?? '').split('x').map(Number)
    if (w && (!largest || w * h > largest.w * largest.h)) largest = { w, h }
  }
  return { mb: statSync(file).size / 1048576, tris, textures: textures.length, largest: largest ? `${largest.w}×${largest.h}` : '—' }
}

const files = readdirSync(OUT).filter((f) => f.endsWith('.glb')).sort()
const rows = []
for (const f of files) {
  const id = f.slice(0, -4)
  process.stdout.write(`${id} … `)
  try {
    rows.push({ id, ...stats(join(OUT, f)) })
    console.log('ok')
  } catch (e) {
    rows.push({ id, error: String(e.message).split('\n')[0] })
    console.log('inspect failed')
  }
}

// second pass for heavy geometry
const simplified = []
for (const r of rows.filter((r) => r.tris > TRI_LIMIT)) {
  const raw = join(RAW, `${r.id}.glb`)
  if (!existsSync(raw)) {
    simplified.push({ id: r.id, before: r, error: 'raw file missing' })
    continue
  }
  process.stdout.write(`simplify ${r.id} … `)
  const tmp = join(OUT, `${r.id}.simplified.tmp.glb`)
  try {
    run([
      'optimize', raw, tmp,
      '--compress', 'meshopt', '--texture-compress', 'webp', '--texture-size', '2048',
      '--prune', 'true', '--weld', 'true',
      '--simplify', 'true', '--simplify-ratio', '0.5', '--simplify-error', '0.001',
      '--join', 'false', '--instance', 'false', '--flatten', 'false', '--palette', 'false',
    ])
    const after = stats(tmp)
    renameSync(tmp, join(OUT, `${r.id}.glb`))
    simplified.push({ id: r.id, before: { ...r }, after })
    Object.assign(r, after)
    console.log(`${r.tris.toLocaleString('en')} tris`)
  } catch (e) {
    simplified.push({ id: r.id, before: r, error: String(e.message).split('\n')[0] })
    console.log('failed')
  }
}

const fmtTris = (n) => (n == null ? '—' : n.toLocaleString('en'))
const total = rows.reduce((s, r) => s + (r.mb ?? 0), 0)
const untextured = rows.filter((r) => r.textures === 0)
const big = rows.filter((r) => r.mb > MB_LIMIT)
const heavy = rows.filter((r) => r.tris > TRI_LIMIT)

let md = `# Model quality report\n\nGenerated by \`npm run models:report\` from \`public/models\` (${rows.length} models, ${total.toFixed(1)} MB total).\n\n`
md += `## Flags\n\n`
md += `**No textures (${untextured.length})**, possibly untextured; they render with their base material colours only:\n${untextured.length ? untextured.map((r) => `- \`${r.id}\` (${names.get(r.id)})`).join('\n') : '- none'}\n\n`
md += `Specifically checked: ${WATCH.map((id) => {
  const r = rows.find((x) => x.id === id)
  return r ? `\`${id}\` ${r.textures === 0 ? '**0 textures**' : `${r.textures} textures`}` : `\`${id}\` not present`
}).join(' · ')}\n\n`
md += `**Over ${MB_LIMIT} MB after optimisation (${big.length})**:\n${big.length ? big.map((r) => `- \`${r.id}\`: ${r.mb.toFixed(1)} MB`).join('\n') : '- none'}\n\n`
md += `**Over ${(TRI_LIMIT / 1000).toFixed(0)}k triangles, simplified (ratio 0.5, error 0.001)**:\n`
md += simplified.length
  ? `\n| id | before | after |\n|---|---|---|\n${simplified.map((s) => `| \`${s.id}\` | ${fmtTris(s.before.tris)} tris, ${s.before.mb.toFixed(1)} MB | ${s.after ? `${fmtTris(s.after.tris)} tris, ${s.after.mb.toFixed(1)} MB` : `not simplified: ${s.error}`} |`).join('\n')}\n`
  : '- none\n'
if (heavy.length) md += `\nStill over ${(TRI_LIMIT / 1000).toFixed(0)}k after the second pass: ${heavy.map((r) => `\`${r.id}\``).join(', ')}\n`
md += `\n## All models\n\n| id | firearm | size (MB) | triangles | textures | largest texture |\n|---|---|---:|---:|---:|---|\n`
for (const r of rows) {
  md += r.error
    ? `| \`${r.id}\` | ${names.get(r.id) ?? ''} | — | — | — | inspect failed: ${r.error} |\n`
    : `| \`${r.id}\` | ${names.get(r.id) ?? ''} | ${r.mb.toFixed(1)} | ${fmtTris(r.tris)} | ${r.textures} | ${r.largest} |\n`
}
writeFileSync(join(root, 'data', 'MODEL-REPORT.md'), md)
console.log(`\nWrote data/MODEL-REPORT.md: ${untextured.length} untextured, ${big.length} over ${MB_LIMIT} MB, ${simplified.length} simplified, total ${total.toFixed(1)} MB.`)
